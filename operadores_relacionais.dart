void main() {
  int numeroA = 5;
  int numeroB = 2;
  numeroA > numeroB ? print ("O número A é maior que o número B") : print ("O número A não é maior que o número B");
  numeroA < numeroB ? print ("O número A é menor que o número B") : print ("O número A não é menor que o número B");
  numeroA == numeroB ? print ("O número A é igual ao número B") : print ("O número A não é igual ao número B");
  numeroA != numeroB ? print ("O número A é diferente do número B") : print ("O número A não é  diferente do número B");
}

